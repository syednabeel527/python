# if and else condition simple example

age = int(input("Enter the age of the person : "))
if age >= 18:
    print("You can vote")
else : 
    print("You can't vote")


# elif example 

color = input("Enter the name of the color : ")
if color == "red":
    print("Stop")
elif color == "yellow":
    print("Wait")
elif color == "green":
    print("Go")
else :
    print("Wrong color for traffic light")